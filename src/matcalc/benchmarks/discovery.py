"""The Matbench Discovery data files the benchmark reads (Figshare article 22715158, CC BY 4.0)."""

MAX_E_FORM_ERROR = 5.0
"""Predicted formation energies further than this from DFT (eV/atom) count as missing (Matbench Discovery)."""


def _tolerance(symprec: float) -> str:
    """``1e-05`` → ``"1e-5"``, as in Matbench Discovery's labels."""
    mantissa, exponent = f"{symprec:.0e}".split("e")
    return f"{mantissa}e{int(exponent)}"


SYMMETRY_COLUMNS = tuple(
    f"{quantity}_{_tolerance(symprec)}" for symprec in SYMPRECS for quantity in ("spg_num", "n_sym_ops")
)
"""Space group number and number of symmetry operations at each tolerance, e.g. ``spg_num_1e-5``."""

QUANTITIES = ("e_form_per_atom", "e_above_hull", "rmsd", *SYMMETRY_COLUMNS)

_MATERIAL_ID = re.compile(r'"material_id"\s*:\s*"([^"]+)"')


class DiscoveryBenchmark(Benchmark):
    """Energy above the convex hull ``e_above_hull`` (eV/atom) and relaxed geometry of WBM crystals.

    Attributes:
        fmax: Force threshold of the relaxations (eV/Å).
        max_steps: Maximum number of FIRE steps per relaxation.
        reference_energies: Materials Project elemental reference energies (eV/atom).
    """

    name = "discovery"
    id_column = "material_id"
    default_dataset = "matbench-discovery-wbm"
    reference_columns = ("e_form_per_atom", "e_above_hull", *SYMMETRY_COLUMNS)
    default_chunk_size = 100
    batched_chunk_size = 25_000

    def __init__(
        self,
        dataset: str | Path | None = None,
        *,
        n_samples: int | None = None,
        seed: int = 42,
        fmax: float = 0.05,
        max_steps: int = 500,
        workers: int = 1,
    ) -> None:
        """
        Args:
            dataset: ``"matbench-discovery-wbm"`` (downloaded from Figshare on first use), or a local
                directory (a ``pathlib.Path``) holding the files of ``WBM_FILES`` under their names.
            n_samples: Draw this many crystals at random (``None`` = all 256,963).
            seed: Seed of the random draw.
            fmax: Force threshold of the relaxations (eV/Å).
            max_steps: Maximum number of FIRE steps per relaxation.
            workers: Processes for the geometry comparison (see ``Benchmark``).
        """
        self.fmax = fmax
        self.max_steps = max_steps
        self.reference_energies: dict[str, float] = {}
        super().__init__(dataset, n_samples=n_samples, seed=seed, workers=workers)

    def run_settings(self) -> dict[str, str]:
        """The relaxation settings that differ from the defaults.

        Returns:
            Setting name → value, kept in the checkpoint so that a run is not resumed with other settings.
        """
        return self._changed_settings("fmax", "max_steps")

    def load_materials(self) -> list[Material]:
        """Read the WBM data; only the structures of the crystals drawn are parsed.

        Returns:
            The crystals of this run, in the order they were drawn.
        """
        files = self._files()
        summary = pd.read_csv(files["summary"], index_col="material_id")
        for symprec, key in zip(SYMPRECS, ("dft_symmetry_1e-5", "dft_symmetry_1e-2"), strict=True):
            symmetry = pd.read_csv(files[key], index_col="material_id", usecols=["material_id", "spg_num", "n_sym_ops"])
            summary[f"spg_num_{_tolerance(symprec)}"] = symmetry["spg_num"]
            summary[f"n_sym_ops_{_tolerance(symprec)}"] = symmetry["n_sym_ops"]
        with gzip.open(files["elemental_references"], "rt") as f:
            self.reference_energies = {
                element: entry["energy"] / sum(entry["composition"].values()) for element, entry in json.load(f).items()
            }
        chosen = sample_subset(list(summary.index), self.n_samples, self.seed)  # same draw as the other benchmarks
        wanted = set(chosen)
        initial = {
            material_id: _atoms(entry["initial_structure"])
            for material_id, entry in _jsonl_entries(files["initial_structures"], wanted)
        }
        relaxed, entries = {}, {}
        for material_id, entry in _jsonl_entries(files["dft_entries"], wanted):
            dft_entry = entry["computed_structure_entry"]
            relaxed[material_id] = _atoms(dft_entry["structure"])
            if {"O", "S"} & set(dft_entry["composition"]):  # the corrections that depend on the structure
                entries[material_id] = {"energy": dft_entry["energy"], "parameters": dft_entry["parameters"]}
        rows = summary.loc[chosen].reset_index().to_dict("records")
        return [
            Material(
                row["material_id"],
                str(row["formula"]),
                initial[row["material_id"]],
                reference={
                    "e_form_per_atom": float(row["e_form_per_atom_mp2020_corrected"]),
                    "e_above_hull": float(row["e_above_hull_mp2020_corrected_ppd_mp"]),
                    "structure": relaxed[row["material_id"]],
                    **{column: _number(row[column]) for column in SYMMETRY_COLUMNS},
                },
                settings={
                    "energy_correction_per_atom": float(row["e_correction_per_atom_mp2020"]),
                    "unique_prototype": bool(row["unique_prototype"]),
                    "dft_entry": entries.get(row["material_id"]),
                },
            )
            for row in rows
        ]

    def evaluate(self, materials: Sequence[Material], simulator: Simulator) -> list[dict[str, Any]]:
        """Steps 1-4 for some crystals.

        Args:
            materials: Crystals to evaluate.
            simulator: The simulator of this run.

        Returns:
            Per crystal: ``e_form_per_atom`` and ``e_above_hull`` (eV/atom), ``rmsd``, the space group and
            number of symmetry operations of the relaxed structure at both tolerances, ``status`` and
            ``relax_steps``.
        """
        with self.stage("relax"):
            relaxed = simulator.relax([m.structure for m in materials], fmax=self.fmax, max_steps=self.max_steps)
        predictions = [self._predict(m, r) for m, r in zip(materials, relaxed, strict=True)]
        done = [(i, r.structure) for i, r in enumerate(relaxed) if r.structure is not None]
        # RMSD, symmetry and the structure-dependent MP2020 corrections need only the CPU: in the worker
        # processes.
        with self.worker_pool() as pool, self.stage("geometry"):
            jobs = [
                (structure, materials[i].reference["structure"], materials[i].settings["dft_entry"])
                for i, structure in done
            ]
            for (i, structure), (comparison, correction) in zip(
                done, pool_map(pool, _compare_geometry, jobs), strict=True
            ):
                if correction is None:
                    predictions[i]["status"] += " (MP2020 correction of the relaxed structure failed)"
                elif correction:
                    shift = correction / len(structure)
                    predictions[i]["e_form_per_atom"] += shift
                    predictions[i]["e_above_hull"] += shift
                if isinstance(comparison, str):
                    predictions[i]["status"] += f" (geometry comparison failed: {comparison})"
                    continue
                predictions[i]["rmsd"] = comparison.rmsd
                for k, symprec in enumerate(SYMPRECS):
                    predictions[i][f"spg_num_{_tolerance(symprec)}"] = comparison.space_groups[k]
                    predictions[i][f"n_sym_ops_{_tolerance(symprec)}"] = comparison.n_symmetry_operations[k]
        return predictions

    def summarize(self, table: pd.DataFrame, model_name: str) -> dict[str, Any]:
        """Matbench Discovery's metrics for one model.

        Discovery metrics, for all crystals and for the unique prototypes (crystals whose prototype is
        not in the Materials Project), use the leaderboard conventions: predictions more than
        ``MAX_E_FORM_ERROR`` from DFT count as missing, missing predictions count as unstable, energies
        are rounded to 1 meV/atom, and the DAF of the unique prototypes divides by the fraction of stable
        crystals before rounding. Geometry metrics cover every relaxed structure at both tolerances.

        Args:
            table: Result of ``run``.
            model_name: The label used in ``run``.

        Returns:
            Counts, ``discovery`` (``full_test_set``, ``unique_prototypes``), ``geo_opt`` (one entry per
            tolerance) and the wall time per stage (s).
        """
        status = table[f"status_{model_name}"].astype(str)
        e_form_dft = pd.to_numeric(table["e_form_per_atom_DFT"], errors="coerce")
        e_hull_dft = pd.to_numeric(table["e_above_hull_DFT"], errors="coerce")
        e_form = pd.to_numeric(table[f"e_form_per_atom_{model_name}"], errors="coerce")
        e_form = e_form.mask((e_form - e_form_dft).abs() > MAX_E_FORM_ERROR).round(3)
        e_hull_true = e_hull_dft.round(3)
        e_hull_pred = e_hull_true + e_form - e_form_dft.round(3)
        unique = table["unique_prototype"].astype(bool).to_numpy()
        discovery = {
            "full_test_set": stability_metrics(e_hull_true, e_hull_pred),
            "unique_prototypes": stability_metrics(
                e_hull_true[unique],
                e_hull_pred[unique],
                prevalence=float(np.mean(e_hull_dft[unique] <= STABILITY_THRESHOLD)),
            ),
        }
        relaxed = status.str.startswith(OK).to_numpy()
        geo_opt = {
            f"symprec={_tolerance(symprec)}": geometry_metrics(
                pd.to_numeric(table[f"rmsd_{model_name}"], errors="coerce")[relaxed],
                pd.to_numeric(table[f"spg_num_{_tolerance(symprec)}_{model_name}"], errors="coerce")[relaxed],
                pd.to_numeric(table[f"spg_num_{_tolerance(symprec)}_DFT"], errors="coerce")[relaxed],
                pd.to_numeric(table[f"n_sym_ops_{_tolerance(symprec)}_{model_name}"], errors="coerce")[relaxed],
                pd.to_numeric(table[f"n_sym_ops_{_tolerance(symprec)}_DFT"], errors="coerce")[relaxed],
            )
            for symprec in SYMPRECS
        }
        return {
            "n_materials": len(table),
            "n_ok": int(relaxed.sum()),
            "discovery": discovery,
            "geo_opt": geo_opt,
            "timings_s": dict(self.timings),
        }

    def _row(self, material: Material, prediction: dict[str, Any], model_name: str) -> dict[str, Any]:
        row = super()._row(material, prediction, model_name)
        row["unique_prototype"] = material.settings["unique_prototype"]
        return row

    def _files(self) -> dict[str, Path]:
        if isinstance(self.dataset, Path):
            return {key: self.dataset / file.name for key, file in WBM_FILES.items()}
        if self.dataset != self.default_dataset:
            raise ValueError(f"Unknown dataset {self.dataset!r}: use {self.default_dataset!r} or a Path to a directory")
        return {key: download_figshare_file(file, "matbench-discovery") for key, file in WBM_FILES.items()}

    def _predict(self, material: Material, result: RelaxResult) -> dict[str, Any]:
        steps = {"relax_steps": result.n_steps}
        if result.structure is None or result.error is not None:
            return failed(result.error or "relaxation failed", QUANTITIES) | steps
        composition = Composition(material.formula)
        e_form = (
            formation_energy_per_atom(result.energy, composition, self.reference_energies)
            + material.settings["energy_correction_per_atom"]
        )
        e_hull = material.reference["e_above_hull"] + e_form - material.reference["e_form_per_atom"]
        status = OK if result.optimizer_converged else f"{OK} (not converged after {result.n_steps} steps)"
        missing = dict.fromkeys(QUANTITIES, float("nan"))  # the geometry is filled in by evaluate()
        return missing | {"e_form_per_atom": e_form, "e_above_hull": e_hull, "status": status} | steps


def _compare_geometry(
    job: tuple[Structure, Atoms, dict[str, Any] | None],
) -> tuple[GeometryComparison | str, float | None]:
    """In a worker process: ``compare_geometry`` (or the error message) and the change of the MP2020
    correction (eV per cell; 0 without oxygen or sulfur, ``None`` if pymatgen rejects the entry).
    """
    relaxed, reference_atoms, dft_entry = job
    reference = to_pmg_structure(reference_atoms)
    correction: float | None = 0.0
    if dft_entry is not None:
        try:
            correction = mp2020_correction_change(relaxed, reference, dft_entry["energy"], dft_entry["parameters"])
        except Exception:  # noqa: BLE001 - one crystal must not stop the benchmark
            correction = None
    try:
        return compare_geometry(relaxed, reference), correction
    except Exception as exc:  # noqa: BLE001 - one crystal must not stop the benchmark
        return f"{type(exc).__name__}: {exc}", correction


def _number(value: Any) -> float:
    """A symmetry value from the published tables (NaN where missing)."""
    return float(value) if pd.notna(value) else float("nan")


def _jsonl_entries(path: Path, wanted: set[str]) -> Iterator[tuple[str, dict[str, Any]]]:
    """The entries of a JSON-lines file whose ``material_id`` is wanted (other lines are not parsed)."""
    with gzip.open(path, "rt") as f:
        for line in f:
            match = _MATERIAL_ID.search(line, 0, 200)
            if match is not None and match.group(1) in wanted:
                yield match.group(1), json.loads(line)


def _atoms(structure: dict[str, Any]) -> Atoms:
    """An ordered pymatgen ``Structure`` dict as ASE ``Atoms`` (lighter than ``Structure`` for 250,000 crystals)."""
    sites = structure["sites"]
    if any(len(site["species"]) != 1 or site["species"][0]["occu"] != 1 for site in sites):
        raise ValueError("disordered structure")
    return Atoms(
        numbers=[atomic_numbers[site["species"][0]["element"]] for site in sites],
        cell=structure["lattice"]["matrix"],
        scaled_positions=[site["abc"] for site in sites],
        pbc=True,
    )
