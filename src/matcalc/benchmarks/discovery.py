"""Discovery benchmark: thermodynamic stability of hypothetical WBM crystals (Matbench Discovery).

The discovery and geometry-optimization tasks of Matbench Discovery (J. Riebesell et al., Nat. Mach.
Intell. 7, 836 (2025); data: https://figshare.com/articles/dataset/22715158, CC BY 4.0) on the WBM data
set (H.-C. Wang, S. Botti, M. A. L. Marques, npj Comput. Mater. 7, 12 (2021)): 256,963 crystals generated by element
substitution into known prototypes and relaxed with PBE (+U) in the Materials Project setup.

Recipe:

1. Relax every unrelaxed WBM structure (FIRE on a Frechet cell filter, fmax = 0.05 eV/Å, at most 500
   steps, the protocol of most Matbench Discovery submissions). A relaxation that reaches the step limit
   still gives a prediction, as in Matbench Discovery.
2. Formation energy E_form = (E - Σ_i n_i μ_i) / N + ΔE_MP2020, with the MLIP energy E of the relaxed
   structure, the Materials Project elemental reference energies μ_i and the MP2020 energy correction per
   atom of the relaxed structure, as in Matbench Discovery. The correction is the published one of the
   WBM DFT entry plus the change that the relaxed structure brings (oxide and sulfide types), both
   computed with the same pymatgen: recomputing the whole correction with pymatgen 2026.9 would change it
   for 1.4 % of the entries relative to the published DFT values (matbench-discovery issue #358).
3. Distance to the convex hull E_hull = E_hull(DFT) + E_form - E_form(DFT): the hull of the Materials
   Project phases stays fixed. Stability classification (stable: E_hull <= 0) and regression metrics
   follow Matbench Discovery's conventions (see ``summarize``).
4. Geometry: RMSD between the MLIP-relaxed and the DFT-relaxed structure (pymatgen StructureMatcher) and
   their space groups (moyopy; the DFT ones are those published with the data) at two tolerances.
"""

